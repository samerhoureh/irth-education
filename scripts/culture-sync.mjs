async function sync() {
  let updated = 0;
  for (const [code, def] of Object.entries(PERSONAS)) {
    const country = await db.country.findUnique({ where: { code } });
    if (!country) {
      console.error(`✗ الدولة ${code} غير موجودة`);
      continue;
    }
    await db.country.update({
      where: { code },
      data: { culturePersona: def.persona, curriculumNote: def.note },
    });
    updated++;
    console.log(`✓ ${country.nameAr} (${code}) — حُدّثت الشخصية الثقافية`);
  }
  console.log(`\n✅ تم تخصيب الهوية الثقافية واللهجية لـ${updated} دولة`);
}

sync()
  .catch((e) => {
    console.error('✗ فشل تخصيب الثقافات:', e);
    process.exit(1);
  })
  .finally(() => db.$disconnect());
